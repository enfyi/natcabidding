import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source = await readFile(new URL('../bidding.js', import.meta.url), 'utf8');
const start = source.indexOf('async function attachLeaveRequestWeekBuckets(');
const end = source.indexOf('\nfunction ', start);
const context = vm.createContext({console});
vm.runInContext(source.slice(start,end), context);
const pending = [];
const client = {from: () => ({select: () => ({in: (_, ids) => new Promise(resolve => pending.push({ids,resolve}))})})};
const rows = Array.from({length:201}, (_,id) => ({id,round_number:1,status:'approved'}));
const resultPromise = context.attachLeaveRequestWeekBuckets(client, rows);
assert.equal(pending.length,3, 'All batches start before awaiting any result');
for (const batch of pending) batch.resolve({data:batch.ids.map(id=>({leave_request_id:id,bucket_start_date:'2027-03-21'})),error:null});
const result = await resultPromise;
assert.equal(result.length,201);
for (const row of result) assert.equal(row.weekBucketStarts[0],'2027-03-21');
console.log('Parallel reload batches preserve all leave week details.');
const integrated = [{id:1,round_number:1,status:'approved',weekBucketStarts:['2027-03-21']}];
const noReads = {from:()=>{throw new Error('Unexpected follow-up lookup');}};
assert.equal((await context.attachLeaveRequestWeekBuckets(noReads,integrated))[0].weekBucketStarts[0],'2027-03-21');
const mixedPromise = context.attachLeaveRequestWeekBuckets(client,[...integrated,{id:2,round_number:1,status:'pending'}]);
assert.deepEqual(pending.at(-1).ids,[2]);
pending.at(-1).resolve({data:[{leave_request_id:2,bucket_start_date:'2027-04-04'}],error:null});
const mixed = await mixedPromise;
assert.equal(mixed[0].weekBucketStarts[0],'2027-03-21');
assert.equal(mixed[1].weekBucketStarts[0],'2027-04-04');
const loaderStart = source.indexOf('async function loadLeaveRequestsWithWeeks(');
vm.runInContext(source.slice(loaderStart,source.indexOf('\n}',loaderStart)+2),context);
context.BID_YEAR=2027;
context.isMissingSupabaseRoutine=error=>error?.code==='PGRST202';
for (const error of [null,{code:'PGRST202'},{code:'42501'},{code:'NETWORK'}]) {
 const calls=[];
 const response={data:integrated,error};
 const result=await context.loadLeaveRequestsWithWeeks({rpc:async(name,args)=>{calls.push([name,args.queue_bid_year]);return response;}});
 assert.equal(result,response);
 assert.equal(calls.length,error?.code==='PGRST202'?2:1);
 assert.equal(calls[0][0],'read_leave_intake_queue_with_weeks');
 assert.equal(calls[0][1],2027);
 if(calls.length===2) assert.equal(calls[1][0],'read_leave_intake_queue');
}
console.log('PASS combined responses skip follow-up reads; legacy fallback does not hide access/network errors.');
